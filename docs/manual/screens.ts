/** До какого шага плана сборки описана игра. Печатается на обложке; меняется вместе с планом в AGENTS.md. */
export const GAME_STATE = 'шаги 0–6 плана сборки';

export interface Block {
  /** Значение `data-block` в интерфейсе. */
  id: string;
  title: string;
  /** Что показывает. */
  what: string;
  /** Откуда берутся данные. */
  source: string;
  /** Зачем это здесь. */
  why: string;
}

export interface Action {
  /** Что делает игрок. */
  act: string;
  /** Сколько внимания это стоит. */
  cost: string;
  /** Что меняется в данных и на экранах. */
  effect: string;
}

export interface Screen {
  id: 'people' | 'map' | 'tasks' | 'sheet' | 'turn';
  title: string;
  /** Адрес экрана после «#». */
  route: string;
  /** Одна-две фразы: зачем этот экран. */
  lead: string;
  blocks: Block[];
  actions: Action[];
}

